create extension if not exists pgcrypto;

create table if not exists public.mm2wild_battles (
  id uuid primary key default gen_random_uuid(),
  game_number bigint generated by default as identity unique,
  creator_uuid uuid not null references public.mm2wild_users(uuid) on delete restrict,
  creator_username text not null,
  creator_avatar text not null,
  status text not null default 'open' check (status in ('open', 'in_progress', 'complete', 'cancelled')),
  cases jsonb not null check (jsonb_typeof(cases) = 'array' and jsonb_array_length(cases) between 1 and 100),
  rounds smallint not null check (rounds between 1 and 100),
  player_layout jsonb not null check (jsonb_typeof(player_layout) = 'array'),
  max_players smallint not null check (max_players between 2 and 6),
  players jsonb not null default '[]'::jsonb check (jsonb_typeof(players) = 'array'),
  total_cost numeric(20, 0) not null check (total_cost > 0),
  creator_cost numeric(20, 0) not null check (creator_cost > 0),
  share_mode boolean not null default false,
  crazy_mode boolean not null default false,
  jackpot_mode boolean not null default false,
  partial_funding boolean not null default false,
  funding_percent smallint not null default 0 check (funding_percent between 0 and 100),
  borrow_mode boolean not null default false,
  borrow_percent smallint not null default 0 check (borrow_percent between 0 and 80),
  minimum_level integer not null default 1 check (minimum_level >= 1),
  private boolean not null default false,
  access_key uuid,
  fast_spin boolean not null default false,
  current_round smallint not null default 0 check (current_round >= 0),
  results jsonb not null default '[]'::jsonb check (jsonb_typeof(results) = 'array'),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  check (not (partial_funding and borrow_mode)),
  check ((private and access_key is not null) or (not private and access_key is null))
);

alter table public.mm2wild_battles
  add column if not exists join_cost numeric(20, 0) generated always as (
    greatest(1, case
      when partial_funding then round(total_cost * (100 - funding_percent) / 100)
      when borrow_mode then round(total_cost * (100 - borrow_percent) / 100)
      else total_cost
    end)
  ) stored;

create index if not exists idx_mm2wild_battles_public_status_created
  on public.mm2wild_battles (private, status, created_at desc);
create index if not exists idx_mm2wild_battles_creator_created
  on public.mm2wild_battles (creator_uuid, created_at desc);

alter table public.mm2wild_battles enable row level security;
revoke all on table public.mm2wild_battles from public, anon, authenticated;

create or replace function public.mm2wild_create_battle(
  p_user_uuid uuid,
  p_cases jsonb,
  p_rounds integer,
  p_player_layout jsonb,
  p_max_players integer,
  p_total_cost numeric,
  p_creator_cost numeric,
  p_share_mode boolean,
  p_crazy_mode boolean,
  p_jackpot_mode boolean,
  p_partial_funding boolean,
  p_funding_percent integer,
  p_borrow_mode boolean,
  p_borrow_percent integer,
  p_minimum_level integer,
  p_private boolean,
  p_fast_spin boolean
) returns public.mm2wild_battles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user public.mm2wild_users%rowtype;
  v_battle public.mm2wild_battles%rowtype;
  v_cost numeric(20, 0);
  v_expected_cost numeric(20, 0);
  v_access_key uuid;
begin
  if jsonb_typeof(p_cases) <> 'array' or jsonb_array_length(p_cases) < 1
     or jsonb_array_length(p_cases) > 100 or p_rounds < 1 or p_rounds > 100 then
    raise exception using errcode = 'P0001', message = 'Choose between 1 and 100 battle rounds.';
  end if;
  if jsonb_typeof(p_player_layout) <> 'array' or p_max_players < 2 or p_max_players > 6 then
    raise exception using errcode = 'P0001', message = 'Choose a valid player layout.';
  end if;
  if p_total_cost is null or p_total_cost <= 0 or p_total_cost <> trunc(p_total_cost)
     or p_creator_cost is null or p_creator_cost <= 0 or p_creator_cost <> trunc(p_creator_cost) then
    raise exception using errcode = 'P0001', message = 'The battle cost is invalid.';
  end if;
  if coalesce(p_partial_funding, false) and coalesce(p_borrow_mode, false) then
    raise exception using errcode = 'P0001', message = 'Partial funding and borrow cannot be combined.';
  end if;

  v_expected_cost := case
    when coalesce(p_partial_funding, false) then
      p_total_cost + round(p_total_cost * (p_max_players - 1) * p_funding_percent / 100)
    when coalesce(p_borrow_mode, false) then
      greatest(1, round(p_total_cost * (100 - p_borrow_percent) / 100))
    else p_total_cost
  end;
  if p_creator_cost <> v_expected_cost then
    raise exception using errcode = 'P0001', message = 'The creator cost is invalid.';
  end if;

  v_cost := p_creator_cost;
  update public.mm2wild_users
     set mm2_balance = mm2_balance - v_cost,
         total_wagered = total_wagered + v_cost,
         total_bets = total_bets + 1
   where uuid = p_user_uuid and mm2_balance >= v_cost
   returning * into v_user;
  if v_user.uuid is null then
    raise exception using errcode = 'P0001', message = 'Insufficient balance.';
  end if;

  v_access_key := case when coalesce(p_private, false) then gen_random_uuid() else null end;
  insert into public.mm2wild_battles (
    creator_uuid, creator_username, creator_avatar, cases, rounds,
    player_layout, max_players, players, total_cost, creator_cost,
    share_mode, crazy_mode, jackpot_mode, partial_funding, funding_percent,
    borrow_mode, borrow_percent, minimum_level, private, access_key, fast_spin
  ) values (
    v_user.uuid, v_user.username, v_user.avatar_headshot, p_cases, p_rounds,
    p_player_layout, p_max_players,
    jsonb_build_array(jsonb_build_object(
      'uuid', v_user.uuid, 'username', v_user.username,
      'avatar', v_user.avatar_headshot, 'level', v_user.level, 'slot', 0
    )),
    p_total_cost, v_cost,
    coalesce(p_share_mode, false), coalesce(p_crazy_mode, false), coalesce(p_jackpot_mode, false),
    coalesce(p_partial_funding, false), case when p_partial_funding then p_funding_percent else 0 end,
    coalesce(p_borrow_mode, false), case when p_borrow_mode then p_borrow_percent else 0 end,
    greatest(coalesce(p_minimum_level, 1), 1), coalesce(p_private, false), v_access_key,
    coalesce(p_fast_spin, false)
  ) returning * into v_battle;

  return v_battle;
end;
$$;

revoke all on function public.mm2wild_create_battle(
  uuid, jsonb, integer, jsonb, integer, numeric, numeric, boolean, boolean,
  boolean, boolean, integer, boolean, integer, integer, boolean, boolean
) from public, anon, authenticated;
grant execute on function public.mm2wild_create_battle(
  uuid, jsonb, integer, jsonb, integer, numeric, numeric, boolean, boolean,
  boolean, boolean, integer, boolean, integer, integer, boolean, boolean
) to service_role;
